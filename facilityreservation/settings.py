def load_environment_file(path):
    """Load simple KEY=VALUE entries without overriding shell variables."""
    if not path.exists():
        return

    for raw_line in path.read_text(encoding='utf-8').splitlines():
        line = raw_line.strip()

        if not line or line.startswith('#') or '=' not in line:
            continue

        key, value = line.split('=', 1)
        key = key.strip()
        value = value.strip()

        if value[:1] == value[-1:] and value.startswith(('"', "'")):
            value = value[1:-1]

        os.environ.setdefault(key, value)


def environment_boolean(name, default=False):
    value = os.environ.get(name)

    if value is None:
        return default

    normalized_value = value.strip().lower()

    if normalized_value in {'1', 'true', 'yes', 'on'}:
        return True

    if normalized_value in {'0', 'false', 'no', 'off'}:
        return False

    raise ImproperlyConfigured(
        f'{name} must be a boolean value.'
    )


def environment_integer(name, default, minimum=None):
    raw_value = os.environ.get(name)

    if raw_value is None:
        return default

    try:
        value = int(raw_value)
    except ValueError as error:
        raise ImproperlyConfigured(
            f'{name} must be an integer.'
        ) from error

    if minimum is not None and value < minimum:
        raise ImproperlyConfigured(
            f'{name} must be at least {minimum}.'
        )

    return value


def environment_list(name, default=''):
    raw_value = os.environ.get(name, default)
    return [
        item.strip()
        for item in raw_value.split(',')
        if item.strip()
    ]


